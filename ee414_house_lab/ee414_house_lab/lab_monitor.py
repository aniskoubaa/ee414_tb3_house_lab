#!/usr/bin/env python3
"""The lab monitor: it watches your robot and writes the numbers for your report.

You do not edit this file. You run it next to your own program:

    ./lab monitor 1                    Lab 1: watch the wanderer for 3 minutes
    ./lab monitor 1 --minutes 5        ... or for 5
    ./lab monitor 3 --goal 3.0 0.0     Lab 3: watch a run to the goal (odom x y)

It only LISTENS (to /scan, /odom, /cmd_vel and /ground_truth). It never
drives the robot. /ground_truth is where Gazebo says the robot REALLY is; a
real robot has no such topic. /odom is only what the wheels believe.

It measures:
    time, distance driven
    clearance   = the smallest valid laser reading (how close you came to something)
    close calls = how many times the clearance dropped below 0.20 m
    bumps       = how many times the robot was told to drive but did not really
                  move (it is pushing against something)
    rooms       = which rooms of the house the robot really reached
    odom error  = how far /odom is from the true position at the end
    Lab 3 only: did it REALLY reach the goal (judged by where the robot really
                is, not by /odom), how long it took, the final error

When it ends (time is up, goal reached, or Ctrl-C) it writes into
submission/labN/ :
    labN_run_<time>.txt    the summary   -> copy the numbers into your report
    labN_run_<time>.csv    the trace, one line every 0.2 s
    labN_run_<time>.png    the path on the floor plan
"""

import argparse
import csv
import datetime
import math
import os
import pathlib
import signal
import time

import rclpy
from geometry_msgs.msg import TwistStamped
from nav_msgs.msg import Odometry
from rclpy.node import Node
from rclpy.signals import SignalHandlerOptions
from sensor_msgs.msg import LaserScan

from ee414_house_lab import world_info

CLOSE_CALL = 0.20     # m   clearance below this counts as a close call
BUMP_TIME = 1.5       # s   told to drive, not moving, this long = a bump
GOAL_TOL = 0.20       # m   Lab 3: this close to the goal counts as reached


def results_dir(lab):
    """submission/labN inside the lab repository (or ~/ee414_lab_results/labN)."""
    base = os.environ.get('EE414_LAB_DIR')
    root = pathlib.Path(base) / 'submission' if base else pathlib.Path.home() / 'ee414_lab_results'
    d = root / f'lab{lab}'
    d.mkdir(parents=True, exist_ok=True)
    return d


class Monitor(Node):

    def __init__(self, lab, minutes, goal):
        super().__init__('lab_monitor')
        self.lab, self.goal = lab, goal
        self.limit = minutes * 60.0
        self.create_subscription(LaserScan, '/scan', self.on_scan, 10)
        self.create_subscription(Odometry, '/odom', self.on_odom, 10)
        self.create_subscription(TwistStamped, '/cmd_vel', self.on_cmd, 10)
        self.create_subscription(Odometry, '/ground_truth', self.on_truth, 10)

        self.start = None            # wall time of the first odom message
        self.pos = None              # (x, y) odom: what the wheels believe
        self.true = None             # (x, y) world: where the robot really is
        self.true_hist = []          # recent (time, x, y), for bump detection
        self.cmd_v = 0.0
        self.clear_now = math.inf
        self.clear_min = math.inf
        self.distance = 0.0
        self.close_calls = 0
        self.in_close = False
        self.bumps = 0
        self.stuck_since = None      # time of the last bump still in progress
        self.drive_since = None      # since when the robot has been told to drive forward
        self.rooms = []
        self.goal_time = None
        self.trace = []
        self.done = False
        self.create_timer(0.2, self.tick)

    # ---- listening ------------------------------------------------------
    def on_scan(self, msg):
        valid = [r for r in msg.ranges if math.isfinite(r) and msg.range_min <= r <= msg.range_max]
        self.clear_now = min(valid) if valid else math.inf

    def on_odom(self, msg):
        p = msg.pose.pose.position
        if self.pos is not None:
            self.distance += math.hypot(p.x - self.pos[0], p.y - self.pos[1])
        else:
            self.start = time.monotonic()
            print('  monitor: robot found, recording.')
        self.pos = (p.x, p.y)

    def on_truth(self, msg):
        p = msg.pose.pose.position
        self.true = (p.x, p.y)

    def on_cmd(self, msg):
        self.cmd_v = msg.twist.linear.x

    # ---- measuring ------------------------------------------------------
    def tick(self):
        if self.pos is None or self.done:
            return
        t = time.monotonic() - self.start
        now = time.monotonic()

        self.clear_min = min(self.clear_min, self.clear_now)
        if self.clear_now < CLOSE_CALL and not self.in_close:
            self.close_calls += 1
            print(f'  ! close call at t={t:5.1f} s: {self.clear_now:.2f} m')
        self.in_close = self.clear_now < CLOSE_CALL

        # Where is the robot really? Gazebo's ground truth if we have it,
        # otherwise trust the wheels.
        wx, wy = self.true if self.true else world_info.odom_to_world(*self.pos)

        # A bump: told to drive forward, but it has not really moved for BUMP_TIME.
        self.true_hist = [h for h in self.true_hist if now - h[0] <= BUMP_TIME] + [(now, wx, wy)]
        moved = math.dist(self.true_hist[0][1:], (wx, wy))
        if abs(self.cmd_v) > 0.05:
            self.drive_since = self.drive_since or now
        else:
            self.drive_since = None
        if (t > 3.0 and self.drive_since is not None and now - self.drive_since > BUMP_TIME
                and moved < 0.02):
            if self.stuck_since is None:
                self.bumps += 1
                print(f'  ! BUMP at t={t:5.1f} s, world ({wx:+.2f}, {wy:+.2f}): '
                      'told to drive, but not moving')
            self.stuck_since = now
        elif moved > 0.05:
            self.stuck_since = None

        room = world_info.room_of(wx, wy)
        if room not in self.rooms:
            self.rooms.append(room)
            print(f'  + reached: {room}   (t={t:5.1f} s)')

        if self.goal is not None:
            # Judge by where the robot REALLY is. /odom can "arrive" while the
            # robot is stuck against a box with its wheels spinning.
            err = math.dist((wx, wy), world_info.odom_to_world(*self.goal))
            if self.goal_time is None and err < GOAL_TOL:
                self.goal_time = t
                print(f'  * GOAL reached at t={t:.1f} s')
            if self.goal_time is not None and t > self.goal_time + 3.0:
                self.done = True

        ox, oy = world_info.odom_to_world(*self.pos)
        self.trace.append((round(t, 2), round(self.pos[0], 3), round(self.pos[1], 3),
                           round(ox, 3), round(oy, 3), round(wx, 3), round(wy, 3),
                           round(self.clear_now, 3) if math.isfinite(self.clear_now) else 'inf',
                           round(self.cmd_v, 3)))
        if len(self.trace) % 50 == 0:
            print(f'  t={t:5.0f} s   driven {self.distance:5.1f} m   min clearance '
                  f'{self.clear_min:.2f} m   close calls {self.close_calls}   bumps {self.bumps}')
        if t >= self.limit:
            self.done = True

    # ---- reporting ------------------------------------------------------
    def summary(self):
        t = self.trace[-1][0] if self.trace else 0.0
        lines = [
            f'EE 414 House Lab -- lab {self.lab} monitor',
            f'date                 {datetime.datetime.now():%Y-%m-%d %H:%M:%S}',
            f'user                 {os.environ.get("USER", "?")}',
            f'duration             {t:.1f} s',
            f'distance driven      {self.distance:.2f} m',
            f'min clearance        {self.clear_min:.3f} m',
            f'close calls (<{CLOSE_CALL:.2f} m) {self.close_calls}',
            f'bumps                {self.bumps}',
            f'rooms reached        {len([r for r in self.rooms if r != "outside"])}: '
            + ', '.join(self.rooms),
            f'odom error at end    {self.odom_error():.3f} m   (/odom vs where the robot really is)',
        ]
        if self.goal is not None:
            row = self.trace[-1]
            true_err = math.dist(row[5:7], world_info.odom_to_world(*self.goal))
            odom_err = math.dist(self.pos, self.goal) if self.pos else math.nan
            lines += [
                f'goal (odom)          ({self.goal[0]:.2f}, {self.goal[1]:.2f})',
                f'goal reached         {"YES" if self.goal_time is not None else "NO"}'
                '   (judged by where the robot really is)',
                f'time to goal         '
                + (f'{self.goal_time:.1f} s' if self.goal_time is not None else '-'),
                f'final error          {true_err:.3f} m   (true position to the goal)',
                f'final error by /odom {odom_err:.3f} m   (what the robot believes)',
                f'straight-line dist   {math.dist((0.0, 0.0), self.goal):.2f} m',
            ]
        return '\n'.join(lines) + '\n'

    def odom_error(self):
        if not self.trace:
            return math.nan
        row = self.trace[-1]
        return math.dist(row[3:5], row[5:7])

    def save(self):
        if not self.trace:
            print('  monitor: no data was recorded (was the simulator running?)')
            return
        d = results_dir(self.lab)
        stem = d / f'lab{self.lab}_run_{datetime.datetime.now():%Y%m%d-%H%M%S}'
        text = self.summary()
        stem.with_suffix('.txt').write_text(text)
        with open(stem.with_suffix('.csv'), 'w', newline='') as f:
            w = csv.writer(f)
            w.writerow(['t_s', 'odom_x', 'odom_y', 'odom_in_world_x', 'odom_in_world_y',
                        'true_x', 'true_y', 'clearance_m', 'cmd_v'])
            w.writerows(self.trace)
        self.plot(stem.with_suffix('.png'))
        print('\n' + text)
        print(f'  saved: {stem}.txt / .csv / .png\n')

    def plot(self, path):
        try:
            import matplotlib
            matplotlib.use('Agg')
            import matplotlib.pyplot as plt
        except ImportError:
            print('  (matplotlib missing: no picture)')
            return
        fig, ax = plt.subplots(figsize=(10, 7.5))
        world_info.draw_house(ax)
        ax.plot([r[3] for r in self.trace], [r[4] for r in self.trace], '--',
                color='tab:gray', lw=1.0, label='path according to /odom')
        xs = [row[5] for row in self.trace]
        ys = [row[6] for row in self.trace]
        ax.plot(xs, ys, '-', color='tab:purple', lw=1.8, label='true path')
        ax.plot(xs[-1], ys[-1], 'o', color='tab:purple', ms=8, label='end')
        if self.goal is not None:
            gx, gy = world_info.odom_to_world(*self.goal)
            ax.plot(gx, gy, 'X', color='crimson', ms=14, label='goal')
        if self.lab in (2, 3):                 # these labs stay in the living room
            ax.set_xlim(-5.4, 0.2)
            ax.set_ylim(-0.6, 5.5)
        ax.set_title(f'Lab {self.lab}: {self.distance:.1f} m driven, min clearance '
                     f'{self.clear_min:.2f} m, {self.bumps} bumps')
        ax.legend(loc='best', framealpha=0.85)
        fig.savefig(path, dpi=90, bbox_inches='tight')
        plt.close(fig)


def main():
    parser = argparse.ArgumentParser(description='EE 414 lab monitor')
    parser.add_argument('lab', type=int, choices=[1, 2, 3])
    parser.add_argument('--minutes', type=float, default=None,
                        help='how long to record (default: 3 for lab 1, 5 otherwise)')
    parser.add_argument('--goal', type=float, nargs=2, default=None, metavar=('X', 'Y'),
                        help='Lab 3: the goal in the odom frame')
    args, _ = parser.parse_known_args()
    minutes = args.minutes or (3.0 if args.lab == 1 else 5.0)

    rclpy.init(signal_handler_options=SignalHandlerOptions.NO)
    signal.signal(signal.SIGINT, signal.default_int_handler)
    node = Monitor(args.lab, minutes, tuple(args.goal) if args.goal else None)
    print(f'\n  Lab {args.lab} monitor: recording for up to {minutes:.0f} min. '
          'Ctrl-C ends early (and still saves).\n')
    try:
        while rclpy.ok() and not node.done:
            rclpy.spin_once(node, timeout_sec=0.1)
    except KeyboardInterrupt:
        pass
    finally:
        node.save()
        node.destroy_node()
        rclpy.try_shutdown()


if __name__ == '__main__':
    main()
